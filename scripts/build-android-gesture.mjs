import { rolldown } from 'rolldown';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const androidGestureBundlePath = resolve(root, 'android/exhibition/app/src/main/assets/exhibition-gestures/detector.js');

export async function buildAndroidGestureBundle() {
  const bundle = await rolldown({
    cwd: root,
    input: resolve(root, 'src/exhibition/nativeGestureRuntime.ts'),
    transform: { target: 'chrome69' },
    treeshake: true,
  });
  try {
    const result = await bundle.generate({ format: 'iife', name: 'NativeGestureBundle', exports: 'named',
      banner: '// Generated by scripts/build-android-gesture.mjs. Do not edit; shares the V1.1 gesture detector.',
    });
    if (result.output.length !== 1 || result.output[0].type !== 'chunk') throw new Error('Gesture runtime must be a single offline script');
    return result.output[0].code;
  } finally { await bundle.close(); }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const code = await buildAndroidGestureBundle();
  if (process.argv.includes('--check')) {
    if (await readFile(androidGestureBundlePath, 'utf8') !== code) throw new Error('Android gesture bundle is stale; run scripts/build-android-gesture.mjs');
    console.log('Android gesture bundle matches the current V1.1 detector.');
  } else {
    await mkdir(dirname(androidGestureBundlePath), { recursive: true });
    await writeFile(androidGestureBundlePath, code);
    console.log(`Built offline Android gesture runtime (${Buffer.byteLength(code)} bytes).`);
  }
}
