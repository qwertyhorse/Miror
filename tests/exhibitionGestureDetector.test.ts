import { describe, expect, it } from 'vitest';
import { ExhibitionGestureDetector, type ExhibitionGesture, type ExhibitionGestureHand, type ExhibitionGestureMode } from '../src/exhibition/gestureDetector';

// A frontal hand: wrist, thumb and the four MCP/PIP/DIP/tip chains.
const palm = [
  [0, 0], [-0.04, -0.05], [-0.09, -0.09], [-0.12, -0.14], [-0.16, -0.17],
  [-0.06, -0.17], [-0.065, -0.29], [-0.07, -0.37], [-0.075, -0.44],
  [0, -0.19], [0, -0.32], [0, -0.41], [0, -0.49],
  [0.06, -0.17], [0.065, -0.29], [0.07, -0.37], [0.075, -0.44],
  [0.115, -0.13], [0.13, -0.23], [0.14, -0.3], [0.15, -0.36],
];

function hand(x: number, y = 0.7, handedness = 'Right', closed = false): ExhibitionGestureHand {
  const landmarks = palm.map(([px, py]) => ({ x: x + px * 0.5, y: y + py * 0.5 }));
  if (closed) for (const start of [5, 9, 13, 17]) {
    landmarks[start + 2] = { x: landmarks[start].x + 0.01, y: landmarks[start].y - 0.035 };
    landmarks[start + 3] = { x: landmarks[start].x + 0.01, y: landmarks[start].y + 0.015 };
  }
  return { landmarks, handedness };
}

function rotatingHand(angle: number, scale = 0.5): ExhibitionGestureHand {
  return { handedness: 'Right', landmarks: palm.map(([x, y]) => ({
    x: 0.5 + (x * Math.cos(angle) - y * Math.sin(angle)) * scale,
    y: 0.7 + (x * Math.sin(angle) + y * Math.cos(angle)) * scale,
  })) };
}

function sampledMotion(detector: ExhibitionGestureDetector, fps: number, duration: number, makeHand: (time: number) => ExhibitionGestureHand): ExhibitionGesture[] {
  const events: ExhibitionGesture[] = [];
  for (let frame = 0; frame <= duration * fps / 1_000; frame += 1) {
    const time = frame * 1_000 / fps;
    const event = detector.update(makeHand(time), time, 'wave');
    if (event) events.push(event);
  }
  return events;
}

type Keyframe = [number, number, number?];
function trajectory(detector: ExhibitionGestureDetector, keyframes: Keyframe[], fps = 30, mode: ExhibitionGestureMode = 'wave', makeHand = hand): ExhibitionGesture[] {
  const events: ExhibitionGesture[] = [];
  const start = keyframes[0][0];
  const end = keyframes.at(-1)![0];
  for (let frame = 0; start + frame * 1_000 / fps <= end + 0.01; frame += 1) {
    const time = start + frame * 1_000 / fps;
    let index = keyframes.findIndex(point => point[0] >= time);
    if (index < 0) index = keyframes.length - 1;
    const to = keyframes[index];
    const from = keyframes[Math.max(index - 1, 0)];
    const fraction = to[0] === from[0] ? 0 : (time - from[0]) / (to[0] - from[0]);
    const x = from[1] + (to[1] - from[1]) * fraction;
    const y = (from[2] ?? 0.7) + ((to[2] ?? 0.7) - (from[2] ?? 0.7)) * fraction;
    const event = detector.update(makeHand(x, y), time, mode);
    if (event) events.push(event);
  }
  return events;
}

const wave: Keyframe[] = [[0, 0.4], [250, 0.62], [500, 0.37], [750, 0.62], [1_000, 0.4]];

describe('exhibition gesture detector', () => {
  it.each([15, 30, 60])('recognizes one deliberate open-palm wave at %i FPS', fps => {
    expect(trajectory(new ExhibitionGestureDetector(), wave, fps)).toEqual(['wave']);
  });

  it.each([5, 8, 10, 15])('recognizes a natural wave with a fixed wrist at %i inference FPS', fps => {
    expect(sampledMotion(new ExhibitionGestureDetector(), fps, 2_000,
      time => rotatingHand(Math.sin(time / 1_000 * Math.PI * 4) * Math.PI / 5))).toEqual(['wave']);
  });

  it('recognizes a smaller visible palm without requiring a large arm movement', () => {
    expect(sampledMotion(new ExhibitionGestureDetector(), 10, 2_000,
      time => rotatingHand(Math.sin(time / 1_000 * Math.PI * 4) * Math.PI / 5, 0.25))).toEqual(['wave']);
  });

  it('keeps normal translation recognizable when inference slows to 5 FPS', () => {
    expect(sampledMotion(new ExhibitionGestureDetector(), 5, 2_000,
      time => hand(0.5 + Math.sin(time / 1_000 * Math.PI * 4) * 0.13))).toEqual(['wave']);
  });

  it('does not treat small finger motion on a stationary palm as a wave', () => {
    expect(sampledMotion(new ExhibitionGestureDetector(), 15, 2_000, time => {
      const sample = hand(0.5);
      for (const index of [8, 12, 16, 20]) sample.landmarks[index].x += Math.sin(time / 1_000 * Math.PI * 4) * 0.015;
      return sample;
    })).toEqual([]);
  });

  it('rearams a wrist-fixed wave only after the moving palm has stopped', () => {
    const detector = new ExhibitionGestureDetector();
    expect(sampledMotion(detector, 10, 3_000,
      time => rotatingHand(Math.sin(time / 1_000 * Math.PI * 4) * Math.PI / 5))).toEqual(['wave']);
    for (let time = 3_100; time <= 3_600; time += 100) expect(detector.update(rotatingHand(0), time, 'wave')).toBeNull();
    expect(trajectory(detector, [[3_700, 0], [3_950, Math.PI / 5], [4_200, -Math.PI / 5], [4_450, Math.PI / 5], [4_700, 0]],
      10, 'wave', angle => rotatingHand(angle))).toEqual(['wave']);
  });

  it.each([30, 60])('recognizes horizontal swipes only after a pause at %i FPS', fps => {
    for (const [from, to, event] of [[0.35, 0.65, 'swipe_right'], [0.65, 0.35, 'swipe_left']] as const) {
      const detector = new ExhibitionGestureDetector();
      expect(trajectory(detector, [[0, from], [600, to]], fps, 'swipe')).toEqual([]);
      expect(trajectory(detector, [[600 + 1_000 / fps, to], [1_000, to]], fps, 'swipe')).toEqual([event]);
    }
  });

  it('does not interpret vertical motion, tiny oscillations, or a closed fist as waving', () => {
    expect(trajectory(new ExhibitionGestureDetector(), [[0, 0.4, 0.7], [250, 0.62, 0.5], [500, 0.37, 0.75], [750, 0.62, 0.5]])).toEqual([]);
    expect(trajectory(new ExhibitionGestureDetector(), wave.map(([time, x]) => [time, 0.5 + (x - 0.5) * 0.12]))).toEqual([]);
    expect(trajectory(new ExhibitionGestureDetector(), wave, 30, 'wave', (x, y) => hand(x, y, 'Right', true))).toEqual([]);
  });

  it('does not concatenate motion across a lost hand, changed handedness, or position jump', () => {
    for (const interruption of ['missing', 'other-hand', 'jump', 'gap']) {
      const detector = new ExhibitionGestureDetector();
      expect(trajectory(detector, [[0, 0.4], [250, 0.62]], 30, 'both')).toEqual([]);
      if (interruption === 'missing') detector.update(null, 270, 'both');
      const start = interruption === 'gap' ? 900 : 300;
      const x = interruption === 'jump' ? 0.25 : 0.62;
      const label = interruption === 'other-hand' ? 'Left' : 'Right';
      expect(trajectory(detector, [[start, x], [start + 900, x]], 30, 'both', (px, py) => hand(px, py, label))).toEqual([]);
    }
  });

  it('advances the cooldown while the hand is absent, without retaining the old path', () => {
    const detector = new ExhibitionGestureDetector();
    expect(trajectory(detector, wave)).toEqual(['wave']);
    detector.update(null, 1_050, 'wave');
    detector.update(null, 2_500, 'wave');
    expect(trajectory(detector, wave.map(([time, x]) => [time + 2_600, x]))).toEqual(['wave']);
  });

  it('emits once for a continuous wave lasting longer than the cooldown', () => {
    const frames: Keyframe[] = [[0, 0.4]];
    for (let index = 1; index <= 20; index += 1) frames.push([index * 250, index % 2 ? 0.63 : 0.37]);
    expect(trajectory(new ExhibitionGestureDetector(), frames)).toEqual(['wave']);
  });

  it('allows the next separate wave after the palm stops', () => {
    const detector = new ExhibitionGestureDetector();
    expect(trajectory(detector, [...wave, [1_700, 0.4]])).toEqual(['wave']);
    expect(trajectory(detector, wave.map(([time, x]) => [time + 1_750, x]))).toEqual(['wave']);
  });

  it('does not turn a paused wave into a swipe in wave mode or both mode', () => {
    const paused: Keyframe[] = [[0, 0.4], [250, 0.62], [500, 0.62], [750, 0.37], [1_000, 0.62]];
    for (const mode of ['wave', 'both'] as const) expect(trajectory(new ExhibitionGestureDetector(), paused, 30, mode)).toEqual(['wave']);
  });

  it('isolates swipe and wave modes and discards motion when the mode changes', () => {
    expect(trajectory(new ExhibitionGestureDetector(), [[0, 0.3], [500, 0.7], [1_300, 0.7]], 30, 'wave')).toEqual([]);
    expect(trajectory(new ExhibitionGestureDetector(), wave, 30, 'swipe')).toEqual([]);
    const detector = new ExhibitionGestureDetector();
    trajectory(detector, [[0, 0.4], [250, 0.62]], 30, 'swipe');
    expect(trajectory(detector, [[300, 0.62], [600, 0.37]], 30, 'wave')).toEqual([]);
  });

  it('rejects malformed keypoints and handles duplicate timestamps or clock reset', () => {
    const detector = new ExhibitionGestureDetector();
    expect(detector.update({ landmarks: [{ x: 0.4, y: 0.7 }] }, 0, 'wave')).toBeNull();
    expect(detector.update(hand(0.4), Number.NaN, 'wave')).toBeNull();
    expect(detector.update(hand(0.4), 20, 'wave')).toBeNull();
    expect(detector.update(hand(0.7), 20, 'wave')).toBeNull();
    expect(trajectory(detector, wave)).toEqual(['wave']);
    detector.reset();
    expect(trajectory(detector, wave)).toEqual(['wave']);
  });
});

